// Generates the typed IPC facade from the exported application service API.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"sort"
	"strings"
)

func main() {
	set := token.NewFileSet()
	packages, err := parser.ParseDir(set, ".", func(info os.FileInfo) bool { return !strings.HasSuffix(info.Name(), "_test.go") }, 0)
	if err != nil {
		panic(err)
	}
	var methods []*ast.FuncDecl
	for _, file := range packages["main"].Files {
		for _, declaration := range file.Decls {
			method, ok := declaration.(*ast.FuncDecl)
			if !ok || method.Recv == nil || !method.Name.IsExported() || method.Name.Name == "GetImageDataURL" {
				continue
			}
			receiver, ok := method.Recv.List[0].Type.(*ast.StarExpr)
			if !ok {
				continue
			}
			name, ok := receiver.X.(*ast.Ident)
			if ok && name.Name == "App" {
				methods = append(methods, method)
			}
		}
	}
	sort.Slice(methods, func(i, j int) bool { return methods[i].Name.Name < methods[j].Name.Name })
	text := func(node ast.Node) string {
		var out bytes.Buffer
		_ = format.Node(&out, set, node)
		return out.String()
	}
	var body strings.Builder
	body.WriteString("// Code generated by go run ./scripts/generate-uibridge.go; DO NOT EDIT.\npackage main\nimport (\"clipbox/internal/clipboard\";\"clipbox/internal/storage\";\"clipbox/internal/ocr\")\n")
	var names []string
	for _, method := range methods {
		var args []string
		for _, field := range method.Type.Params.List {
			for _, name := range field.Names {
				args = append(args, name.Name)
			}
		}
		callArgs := ""
		if len(args) > 0 {
			callArgs = ", " + strings.Join(args, ", ")
		}
		fmt.Fprintf(&body, "func (b *UIBridge) %s%s {\n", method.Name.Name, strings.TrimPrefix(text(method.Type), "func"))
		results := method.Type.Results
		switch {
		case results == nil || len(results.List) == 0:
			fmt.Fprintf(&body, "bridgeValue[bool](b,%q%s)\n", method.Name.Name, callArgs)
		case len(results.List) == 2:
			fmt.Fprintf(&body, "return callUIBackend[%s](b,%q%s)\n", text(results.List[0].Type), method.Name.Name, callArgs)
		case text(results.List[0].Type) == "error":
			fmt.Fprintf(&body, "_,err:=callUIBackend[bool](b,%q%s);return err\n", method.Name.Name, callArgs)
		default:
			fmt.Fprintf(&body, "return bridgeValue[%s](b,%q%s)\n", text(results.List[0].Type), method.Name.Name, callArgs)
		}
		body.WriteString("}\n")
		names = append(names, fmt.Sprintf("%q:true", method.Name.Name))
	}
	body.WriteString("var backendMethods=map[string]bool{" + strings.Join(names, ",") + "}\n")
	data, err := format.Source([]byte(body.String()))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("ui_api_generated.go", data, 0644); err != nil {
		panic(err)
	}
}
